# Generated-metadata POSITIONS, not a global pattern. ASTRA 2026-09-06 11:15Z reproduced the defect
# in the first version, which ran one regex over the whole file: an ordinary sentence differing only
# in a date ("The run completed on 2026-09-04" vs "…-09-05") or in a main reference ("verified at
# main abcdef1234" vs "…deadbeef99") normalised EQUAL and was reported stamp-only, so real content
# drift exited 0. A line qualifies as stamp-only only if it IS one of the three generated metadata
# lines and differs ONLY in its date/commit field; every other differing line is content drift.
# The banner is line 0 of every generated markdown file; "Last inventory" is line 4 of INDEX.md
# only. Each pattern captures its permitted VALUES as groups, and everything outside those groups
# must match exactly — so a change anywhere else on the line, of any shape, is content drift.
BANNER_LINE = re.compile(r"^(<!-- GENERATED by scripts/build_sri\.py\s.*?on )(\d{4}-\d{2}-\d{2})( at main )([0-9a-f]{6,40})(.*-->)$")
LAST_INVENTORY_LINE = re.compile(r"^(\*\*Last inventory:\*\* )(\d{4}-\d{2}-\d{2})(.*)$")
PERMITTED_VALUE_GROUPS = {BANNER_LINE: (2, 4), LAST_INVENTORY_LINE: (2,)}


def _outside_permitted_values(pat: "re.Pattern[str]", line: str) -> tuple | None:
    """The line's fixed parts, with only the permitted value groups removed. None if it is not this
    metadata line at all."""
    m = pat.match(line)
    if not m:
        return None
    allowed = PERMITTED_VALUE_GROUPS[pat]
    return tuple(g for i, g in enumerate(m.groups(), 1) if i not in allowed)


def stamp_only_difference(rel: str, on_disk: str, fresh: str) -> bool:
    """True when two versions of a generated file differ ONLY in generated build metadata.

    ASTRA 2026-09-06 11:15Z and 11:33Z, both reproduced by extracting the patterns through AST:
      - a global regex forgave ordinary prose differing only in a date or a main reference;
      - then a per-line rule still forgave a JSON-shaped `"main": "…"` line appearing inside a
        MARKDOWN register, and forgave a changed hex-like token elsewhere on the "Last inventory"
        line, because the normaliser blanked every date/hex on a line it had decided to trust.

    So: the metadata POSITION is fixed (banner = line 0; "Last inventory" = INDEX.md only), the
    permitted VALUES are captured groups, and everything outside those groups must match exactly.
    BUILD.json needs no rule at all — `--check` never compares it. Any other difference, on any
    line, of any shape, is content drift."""
    a, b = on_disk.splitlines(), fresh.splitlines()
    if len(a) != len(b):
        return False
    for i, (la, lb) in enumerate(zip(a, b)):
        if la == lb:
            continue
        if i == 0 and rel.endswith(".md"):
            fa, fb = _outside_permitted_values(BANNER_LINE, la), _outside_permitted_values(BANNER_LINE, lb)
            if fa is not None and fa == fb:
                continue
        # ASTRA 2026-09-06 11:41Z, third boundary: the INDEX-only guard still allowed a line of this
        # SHAPE anywhere in the file, so body prose beginning "**Last inventory:** <date>" would have
        # had its date forgiven. render_index emits the real header at index 3; pin it there.
        if rel == "INDEX.md" and i == 3:
            fa, fb = _outside_permitted_values(LAST_INVENTORY_LINE, la), _outside_permitted_values(LAST_INVENTORY_LINE, lb)
            if fa is not None and fa == fb:
                continue
        return False
    return True


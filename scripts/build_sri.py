def history_is_complete() -> bool:
    """Is this checkout's history whole enough to say when a file was created?

    ROACH 2026-09-06 10:35Z and 11:01Z: `test_timeline_register` failed twice in CI with
    `scripts/build_sri.py` attributed first to #3478's squash and then to #3488's — the attribution
    followed whatever had most recently landed on main. Neither ordering fix could work, because the
    history itself is truncated: this repository's own `ci.yml` recorded on 2026-09-04 (diagnostic
    run 33922175784) that the runner repo is SHALLOW at test time — `is-shallow-repository` = true,
    `.git/shallow` present — DESPITE `fetch-depth: 0`. Under a graft every path looks as though it
    were added at the boundary commit, so a creation date read there is not late or approximate, it
    is wrong.

    A register that would rather say nothing than say something false: when the history is
    truncated the timeline still lists every tool and record, and marks the date and the reason
    UNKNOWN instead of printing the boundary commit's subject as the reason a tool exists.

    ASTRA 2026-09-06 11:15Z: the first version returned `sh(...) != "true"`, and `sh()` returns an
    empty string on a NON-ZERO exit — so a git query that FAILED was read as "history is complete"
    and the register went on to print provenance it could not know. Only an explicit successful
    "false" now means complete; a failure, an empty answer or anything unrecognised means unknown,
    and unknown withholds."""
    if (REPO / ".git" / "shallow").exists():
        return False
    r = subprocess.run(["git", "rev-parse", "--is-shallow-repository"], cwd=str(REPO),
                       capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=120)
    return r.returncode == 0 and r.stdout.strip() == "false"


UNKNOWN_HISTORY = "unknown — truncated checkout"


def first_adds() -> dict[str, tuple[str, str, str]]:
    """path -> (date, commit, subject) of the commit with the EARLIEST COMMITTER DATE that adds it,
    from ONE git walk (12k lines in ~1 s) instead of one `git log` per tool.

    Read this precisely: it is the earliest committer date VISIBLE IN THIS HISTORY, not a claim
    about when the work was done. Committer dates can be rewritten by a rebase, author dates can be
    backdated outright (which is why this no longer uses them), and a squash replaces the original
    commits entirely. No inference about creation, effort or order follows from the string.

    ROACH 2026-09-06 10:35Z, CI run 34026871919: the previous version kept the first row the walk
    emitted. `--reverse` reverses git's default ordering, which over a branchy graph is topological
    and NOT chronological, so on a merge graph — which CI builds for every PR — a later squash
    commit can be emitted before the commit that truly introduced a file. `scripts/build_sri.py`
    was then dated to #3478's squash and given ITS subject as the reason the tool was created. The
    timeline register's whole promise is when a tool was created and why, so an order-dependent
    answer is unacceptable even when it happens to be right. Take the earliest COMMIT TIMESTAMP
    instead: deterministic in any topology, linear or merged.

    After a squash merge the original authoring commits are unreachable from main, so the honest
    answer is the earliest commit in THIS history that adds the path — the squash, whose subject is
    the PR title. That is the intended reading; it simply no longer varies with traversal order."""
    best: dict[str, tuple[int, str, str, str]] = {}
    cur: tuple[int, str, str, str] | None = None
    # %ct/%cd are COMMITTER dates. ASTRA 2026-09-06 11:15Z: the first version used %at/%ad (AUTHOR
    # dates) while calling them commit timestamps. Author dates can be backdated at will and are not
    # a causal order of first introduction; committer dates at least record when the commit entered
    # this history. Neither is a claim about when the work was really done — see the column note.
    # Read full identities; format the display ourselves. %h depends on core.abbrev
    # and the local object database, so Windows and CI emitted different rows.
    for line in sh(["git", "log", "--diff-filter=A", "--name-only", "--format=%x00%ct|%cd|%H|%s", "--date=short"]).splitlines():
        if line.startswith("\0"):
            parts = line[1:].split("|", 3)
            try:
                cur = (int(parts[0]), parts[1], parts[2], parts[3] if len(parts) > 3 else "") if len(parts) >= 3 else None
            except ValueError:
                cur = None
            continue
        p = line.strip()
        if p and cur and (p not in best or cur[0] < best[p][0]):
            best[p] = cur
    return {p: (v[1], v[2][:10], v[3]) for p, v in best.items()}


def latest_nonmerge_path_date(path: str, ref: str = "HEAD") -> str:
    """Latest UTC committer date among non-merge path changes in reachable history.

    This is history metadata, not current-blob age or an experiment execution date.
    Full traversal avoids git log -1 selecting a different simplified parent history
    in GitHub's synthetic merge despite identical input file bytes.
    """
    if not history_is_complete():
        return UNKNOWN_HISTORY
    raw = sh(["git", "log", "--full-history", "--no-merges", "--format=%ct", ref, "--", path])
    if not raw.strip():
        return "—"
    try:
        return datetime.fromtimestamp(max(int(x) for x in raw.splitlines()), timezone.utc).date().isoformat()
    except (ValueError, OverflowError, OSError):
        return "—"


def harvest_timeline(tools: list[dict], blobs: dict[str, str]) -> list[dict]:
    """Jon 2026-09-05: "timelines for when we created tools and why we created them" (and for the
    write-up). One row per tool and per knowledge record: the date it entered git, the commit, and
    the recorded WHY: commit subject for tools; the record's why/question field for knowledge,
    falling back to its commit subject. These are attributed descriptions, not assessments.

    On a truncated checkout (see history_is_complete) the date and reason are marked UNKNOWN rather
    than filled from the graft boundary, which would name the wrong commit as the reason a tool
    exists. The rows themselves stay: what we have is still listed, only the provenance is withheld."""
    whole = history_is_complete()
    adds = first_adds() if whole else {}
    rows: list[dict] = []
    for t in tools:
        d, h, s = adds.get(t["path"], ("", "", ""))
        m = re.search(r"\(#(\d+)\)", s)
        rows.append({"date": d or (t.get("first_commit") if whole else "") or ("—" if whole else UNKNOWN_HISTORY),
                     "kind": "tool", "what": f"`{t['path']}`",
                     "why": (clean(re.sub(r"\s*\(#\d+\)\s*$", "", s), 200) or "(no commit subject in this history)")
                            if whole else UNKNOWN_HISTORY,
                     "commit": h or "—", "pr": f"#{m.group(1)}" if m else "—", "source": src_ref(t["path"], None, blobs)})
    rec_dir = REPO / "workflow" / "knowledge-register" / "records"
    if rec_dir.exists():
        for p in sorted(rec_dir.glob("*.json"), key=lambda p: p.as_posix()):
            rel = p.relative_to(REPO).as_posix()
            d, h, s = adds.get(rel, ("", "", ""))
            try:
                rec = json.loads(p.read_text(encoding="utf-8"))
            except ValueError:
                rec = {}
            m = re.search(r"\(#(\d+)\)", s)
            rows.append({"date": d or ("—" if whole else UNKNOWN_HISTORY), "kind": "knowledge-record",
                         "what": f"`{rel}` {rec.get('id', p.stem)}",
                         "why": clean(str(rec.get("why") or rec.get("question") or s), 200) or (
                             "—" if whole else UNKNOWN_HISTORY),
                         "commit": h or "—", "pr": f"#{m.group(1)}" if m else "—", "source": src_ref(rel, None, blobs)})
    rows.sort(key=lambda r: (r["date"] in ("—", UNKNOWN_HISTORY), r["date"], r["kind"], r["what"]))
    return rows



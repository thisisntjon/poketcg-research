def harvest_manifest(cur: dict, blobs: dict[str, str], today: str) -> list[dict]:
    a_by_path = {a["path"]: a for a in cur.get("a_assets", [])}
    cat: dict[str, dict] = {}
    if CATALOG.exists():
        for line in CATALOG.read_text(encoding="utf-8", errors="replace").splitlines():
            try:
                r = json.loads(line)
                cat[r["path"]] = r
            except (ValueError, KeyError):
                continue
    labels: dict[str, dict] = {}
    if LABELS.exists():
        with LABELS.open(encoding="utf-8", errors="replace", newline="") as f:
            for r in csv.DictReader(f):
                labels[r["path"]] = r
    records = []
    n = 0
    paths = sorted(set(labels) | set(a_by_path))
    for p in paths:
        lab = labels.get(p, {})
        label = lab.get("label", "")
        if label == "REFUSED":
            continue
        kind = lab.get("kind") or cat.get(p, {}).get("kind") or "other"
        cls = CLASS_MAP.get(kind, "other")
        if Path(p).name.startswith("test_"):
            cls = "test"
        # The manifest is the KNOWLEDGE inventory: docs, data, config, and the tools under
        # scripts/ + harness/. Tests, logs, media and library code are censused by curate
        # (workflow/curation/labels.csv) and are not repeated here.
        is_tool = cls == "code" and (p.startswith("scripts/") or p.startswith("ptcg-agent/harness/"))
        if cls not in {"doc", "data", "config"} and not is_tool and p not in a_by_path:
            continue
        if p in a_by_path:
            status, value = "canonical", "A"
        elif label == "SUPERSEDED":
            status, value = "superseded", "C"
        elif label == "ARCHIVE-CANDIDATE":
            status, value = "derived" if lab.get("rule_id", "").startswith("duplicate") else "superseded", "C"
        elif label == "KEEP-STATE":
            status, value = "canonical", "B"
        elif label in {"KEEP-PINNED", "KEEP-REFERENCED"}:
            status, value = "evidence", "B"
        elif label == "KEEP-LIVE":
            status, value = ("canonical" if cls in {"code", "config"} else "evidence"), "B"
        else:
            status, value = "unknown", "B"
        if not (REPO / p).exists():
            continue
        c = cat.get(p, {})
        title = c.get("title") or Path(p).name
        why = a_by_path.get(p, {}).get("why") or (clean(re.sub(r"^#+\s*", "", (c.get("lead") or title)).split(". ")[0], 160) + " (auto: first sentence)")
        n += 1
        rec = {"id": f"a-{n:05d}", "path": p, "title": clean(title, 120), "class": cls, "status": status, "value": value,
               "produced_by": (f"seat {c['seat']}" if c.get("seat") else "operator") + (f", first commit {c['first_commit'][:10]}" if c.get("first_commit") else "") + " (git)",
               "inputs": [], "claims": [], "last_verified": today, "why_it_matters": why,
               "blob": blobs.get(p), "curate_label": label, "curate_rule": lab.get("rule_id", ""), "successor": lab.get("successor", "") or None,
               "supersedes": None, "archived_to": None, "archived_why": None}
        if value == "A":
            rec["next_action"] = a_by_path[p].get("next_action", "")
        records.append(rec)
    return records



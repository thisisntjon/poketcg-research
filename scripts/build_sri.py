# ---------------------------------------------------------------- git + io helpers
def sh(args: list[str]) -> str:
    r = subprocess.run(args, cwd=str(REPO), capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=300)
    return r.stdout if r.returncode == 0 else ""


def blob_map() -> dict[str, str]:
    out: dict[str, str] = {}
    for entry in sh(["git", "ls-files", "-s", "-z"]).split("\0"):
        if not entry.strip():
            continue
        meta, _, path = entry.partition("\t")
        parts = meta.split()
        if len(parts) >= 2 and path:
            out[path] = parts[1]
    return out


def read(rel: str) -> str:
    p = REPO / rel
    return p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""


def cells(line: str) -> list[str]:
    body = line.strip()
    if body.startswith("|"):
        body = body[1:]
    if body.endswith("|"):
        body = body[:-1]
    return [c.strip() for c in body.split("|")]


def is_sep(cs: list[str]) -> bool:
    return bool(cs) and all(re.fullmatch(r":?-{2,}:?", c) for c in cs if c) and any(cs)


def tables(text: str) -> list[dict]:
    """Every markdown table: {'section', 'header', 'rows': [(line_no, cells)]}."""
    out: list[dict] = []
    section = ""
    cur: dict | None = None
    for i, line in enumerate(text.splitlines(), 1):
        if line.startswith("#"):
            section = line.lstrip("# ").strip()
            cur = None
            continue
        if line.lstrip().startswith("|"):
            cs = cells(line)
            if cur is None:
                cur = {"section": section, "header": cs, "rows": [], "line": i}
                out.append(cur)
                continue
            if is_sep(cs):
                continue
            cur["rows"].append((i, cs))
        else:
            cur = None
    return [t for t in out if t["rows"]]


def clean(s: str, n: int = 220) -> str:
    s = re.sub(r"\s+", " ", s.replace("|", "/")).strip()
    return s if len(s) <= n else s[: n - 1] + "…"


def src_ref(rel: str, line: int | None, blobs: dict[str, str]) -> str:
    """`path` L<line> (blob …) — the path stays alone inside the backticks so validate.py's
    G6 gate can resolve it on disk; the line and the blob ride outside."""
    b = blobs.get(rel, "")
    return f"`{rel}`" + (f" L{line}" if line else "") + (f" (blob {b[:10]})" if b else " (UNTRACKED)")



# ---------------------------------------------------------------- gate
VALIDATOR = Path.home() / ".claude" / "skills" / "inventory" / "scripts" / "validate.py"


def run_gate() -> str:
    """The SRI validator's verdict on the layer on disk, as one line for INDEX.md / BUILD.json."""
    if not VALIDATOR.exists():
        return f"validator not found on this host ({VALIDATOR}); see §Re-run"
    r = subprocess.run([sys.executable, str(VALIDATOR), "--manifest", str(OUT / "MANIFEST.jsonl"), "--root", str(REPO),
                        "--claims", str(REG / "CLAIMS.md")], capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=600)
    lines = [ln for ln in (r.stdout or "").splitlines() if ln.strip()]
    summary = next((ln for ln in lines if ln.startswith("records:")), "")
    verdict = "PASS" if r.returncode == 0 else "FAIL"
    fails = [ln.strip() for ln in lines if ln.strip().startswith("FAIL")][:3]
    return f"{verdict} — {summary}" + (" · " + " · ".join(fails) if fails else "")


# ---------------------------------------------------------------- build
def build(gate: str = "not yet run") -> dict[str, str]:
    today = date.today().isoformat()
    main = sh(["git", "rev-parse", "origin/main"]).strip() or "unknown"
    blobs = blob_map()
    cur = json.loads(CURATED.read_text(encoding="utf-8"))
    for a in cur.get("a_assets", []):
        if not (REPO / a["path"]).exists():
            raise SystemExit(f"CURATED.json names a missing A asset: {a['path']}")
    learn = harvest_learnings(blobs)
    claims = harvest_claims(blobs, today)
    qualify_claims(claims, cur, blobs)
    methods = harvest_methods(cur, blobs, today)
    tools = harvest_tools(blobs, today)
    decisions = harvest_decisions(blobs)
    opens = harvest_open(learn, blobs)
    tombs = harvest_tombstones(blobs)
    manifest = harvest_manifest(cur, blobs, today)
    timeline = harvest_timeline(tools, blobs)
    files = render_registers(today, main, learn, claims, methods, tools, decisions, opens, tombs, timeline)
    out: dict[str, str] = {f"registers/{k}": v for k, v in files.items()}
    out["MANIFEST.jsonl"] = "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in manifest)
    out["INVENTORY.md"] = render_inventory(today, main, cur, manifest)
    counts = {"learnings": len(learn), "claims": len(claims), "methods": len(methods), "tools": len(tools), "decisions": len(decisions),
              "open": len(opens), "tombstones": len(tombs), "manifest": len(manifest), "timeline": len(timeline)}
    out["INDEX.md"] = render_index(today, main, cur, counts, gate)
    # exactly one newline at EOF on every text file (CI diff hygiene: "new blank line at EOF")
    for k in list(out):
        if k.endswith(".md"):
            out[k] = out[k].rstrip("\n") + "\n"
    digest = hashlib.sha256("".join(out[k] for k in sorted(out)).encode("utf-8")).hexdigest()
    out["BUILD.json"] = json.dumps({"schema": "ptcg.sri_build/v1", "built": today, "main": main, "counts": counts, "digest": digest,
                                    "surface_coverage": surface_coverage(), "history_complete": history_is_complete(),
                                    "sources": {k: {"path": v, "blob": blobs.get(v)} for k, v in SRC.items()},
                                    "surfaces": {k: {"path": v, "blob": blobs.get(v)} for k, v in SURFACES.items()}}, indent=1) + "\n"
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--require-complete-history", action="store_true",
                    help="with --check, refuse incomplete or unverified Git history before building")
    a = ap.parse_args(argv)
    if a.require_complete_history and not a.check:
        ap.error("--require-complete-history requires --check")
    if a.require_complete_history and not history_is_complete():
        print("SRI_CHECK HISTORY UNVERIFIED: complete Git history is required; no build or comparison performed")
        return 2
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")  # type: ignore[attr-defined]
    except (AttributeError, ValueError):
        pass
    stored_gate = "not yet run"
    if (OUT / "BUILD.json").exists():
        try:
            stored_gate = json.loads((OUT / "BUILD.json").read_text(encoding="utf-8")).get("gate", stored_gate)
        except ValueError:
            pass
    out = build(stored_gate if a.check else "not yet run")
    if a.check:
        # Two kinds of difference, and only one of them is a defect. The banner carries the build
        # DATE and the main COMMIT, both of which go stale on every merge and every midnight
        # without a single register row changing: that is staleness, not drift. A row whose text or
        # provenance blob differs IS drift — on 2026-09-06 main carried three knowledge-record rows
        # pointing at blobs that #3478 had replaced, and the old undifferentiated "advisory" line
        # hid them among stamp noise. Content drift exits 1; stamp-only staleness reports and
        # exits 0, so this check is safe to run as a gate.
        content_drift, stamp_only = [], []
        for rel, content in out.items():
            if rel == "BUILD.json":
                continue
            p = OUT / rel
            if not p.exists():
                content_drift.append(f"{rel} missing")
                continue
            on_disk = p.read_text(encoding="utf-8").replace("\r\n", "\n")
            if on_disk == content:
                continue
            (stamp_only if stamp_only_difference(rel, on_disk, content) else content_drift).append(f"{rel} differs")
        for d in stamp_only:
            print(f"SRI_CHECK STALE-STAMP (build date / main commit only, not a defect): {d}")
        if content_drift:
            for d in content_drift:
                print(f"SRI_CHECK CONTENT DRIFT: {d}")
                rel = d.removesuffix(" differs")
                if rel in out and (OUT / rel).is_file():
                    old = (OUT / rel).read_text(encoding="utf-8").splitlines()
                    new = out[rel].splitlines()
                    for i in range(max(len(old), len(new))):
                        a_line = old[i] if i < len(old) else "<EOF>"
                        b_line = new[i] if i < len(new) else "<EOF>"
                        if a_line != b_line:
                            print(f"  first difference line {i + 1}; stored: {a_line[:300]!r}; expected: {b_line[:300]!r}")
                            break
            print(f"SRI_CHECK FAIL: {len(content_drift)} file(s) differ in content — run `python scripts/build_sri.py` and commit the result")
            return 1
        print(f"SRI_CHECK OK{f' ({len(stamp_only)} file(s) stale-stamp only)' if stamp_only else ''}")
        return 0
    REG.mkdir(parents=True, exist_ok=True)
    for rel, content in out.items():
        p = OUT / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content, encoding="utf-8", newline="\n")
    # Gate the layer just written and stamp the verdict into INDEX.md + BUILD.json so the map
    # says what the validator said, not "run the validator".
    gate = run_gate()
    b = json.loads(out["BUILD.json"])
    b["gate"] = gate
    (OUT / "BUILD.json").write_text(json.dumps(b, indent=1) + "\n", encoding="utf-8", newline="\n")
    cur = json.loads(CURATED.read_text(encoding="utf-8"))
    (OUT / "INDEX.md").write_text(render_index(b["built"], b["main"], cur, b["counts"], gate).rstrip("\n") + "\n", encoding="utf-8", newline="\n")
    print(f"SRI written: {OUT.relative_to(REPO).as_posix()}/ " + " · ".join(f"{k} {v}" for k, v in b["counts"].items()) + f" · INDEX {len(out['INDEX.md'].splitlines())} lines · digest {b['digest'][:16]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

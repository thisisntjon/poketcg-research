COMMAND_RE = re.compile(r"^(python|py|git|gh|uv|pip|powershell|pwsh|\.\\|\./)\b")


def classify_producers(spans: list[str], blobs: dict[str, str]) -> tuple[list[str], list[str], list[str], list[str]]:
    """Backticked spans -> (repo paths that exist, off-repo paths, commands, unresolved names)."""
    repo, off, cmds, unresolved = [], [], [], []
    bm = basename_map(blobs)
    for s in spans:
        s = s.strip()
        if COMMAND_RE.match(s):
            cmds.append(s)
        elif re.match(r"^[A-Za-z]:[\\/]|^https?://|^~|^/", s):
            off.append(s)
        elif "/" in s or "\\" in s:
            (repo if (REPO / s).exists() else unresolved).append(s)
        elif re.search(r"\.\w{2,5}$", s):
            hits = bm.get(s, [])
            if len(hits) == 1:
                repo.append(hits[0])
            else:
                unresolved.append(s)
    return repo, off, cmds, unresolved


def verify_claim(value: str, spans: list[str], today: str, blobs: dict[str, str]) -> tuple[str, str]:
    """(status, how-to-recheck). Status is about WHERE the number can be read today:
    VERIFIED-AT-ARTIFACT — its numeric tokens were found in a named repo artifact;
    UNVERIFIABLE-HERE — the producer is a command or an off-repo path (re-run / open elsewhere);
    RECEIPT-WEAK — no producer resolves to a repo artifact carrying the tokens."""
    toks = [t.replace(",", "") for t in NUM_TOKEN.findall(value)]
    repo, off, cmds, unresolved = classify_producers(spans, blobs)
    if not toks:
        return "RECEIPT-WEAK", "no numeric token in the value cell"
    for p in repo:
        f = REPO / p
        if f.is_file() and f.suffix.lower() in {".md", ".json", ".jsonl", ".csv", ".txt", ".py"}:
            try:
                text = f.read_text(encoding="utf-8", errors="replace").replace(",", "")
            except OSError:
                continue
            if all(t.lstrip("+-−") in text for t in toks):
                return f"VERIFIED-AT-ARTIFACT {today}", f"tokens found in `{p}`"
    if cmds:
        return "UNVERIFIABLE-HERE", "producer is a command — re-run: " + clean("; ".join(cmds), 140)
    if off:
        return "UNVERIFIABLE-HERE", "producer is off-repo: " + clean("; ".join(off), 120)
    if repo:
        return "RECEIPT-WEAK", "named artifact exists but does not carry the tokens: " + clean("; ".join(repo), 120)
    if unresolved:
        return "RECEIPT-WEAK", "producer name does not resolve to one tracked file: " + clean("; ".join(unresolved), 120)
    return "RECEIPT-WEAK", "no producer named in the row"


